import CryptoKit
import Foundation

/// The complete CK-free identity of one asset slot in one local store.
public struct CloudDataAssetReference: Sendable, Hashable {
  /// The local store that owns the model instance.
  public let storeID: CloudDataStoreID

  /// The stable remote record type.
  public let recordType: String

  /// The stable remote record name.
  public let recordName: String

  /// The stable CKRecord field key declared by `@CloudAsset`.
  public let fieldKey: String

  /// The application identifier returned by the computed `CloudAssetSlot`.
  public let localIdentifier: String

  public init(
    storeID: CloudDataStoreID,
    recordType: String,
    recordName: String,
    fieldKey: String,
    localIdentifier: String
  ) {
    self.storeID = storeID
    self.recordType = recordType
    self.recordName = recordName
    self.fieldKey = fieldKey
    self.localIdentifier = localIdentifier
  }
}

/// A remote asset value ready for consumer-owned final installation.
public enum CloudDataIncomingAssetAction: Sendable, Hashable {
  /// Copy the package-owned read-only source into the application's final
  /// location. The source remains package-owned and must not be moved.
  case replace(packageFileURL: URL)

  /// Apply the application's retention policy for a remotely absent field.
  case remove
}

/// CK-free filesystem hooks supplied by the consuming application.
///
/// The package owns queueing, retry, and temporary files. The consumer owns
/// source resolution, final paths, retention, and any domain bookkeeping.
public struct CloudDataAssetStore: Sendable {
  public typealias OutgoingMaterializer =
    @Sendable (CloudDataAssetReference, URL) async throws -> Void
  public typealias IncomingInstaller =
    @Sendable (CloudDataAssetReference, CloudDataIncomingAssetAction) async throws -> Void

  private let outgoingMaterializer: OutgoingMaterializer
  private let incomingInstaller: IncomingInstaller

  /// Creates the filesystem boundary used by every configured local store.
  ///
  /// `materializeOutgoing` must create a regular file at the supplied package
  /// destination and relinquish it when the closure returns. `installIncoming`
  /// must be idempotent because a committed install is retried after failure or
  /// process termination.
  public init(
    materializeOutgoing: @escaping OutgoingMaterializer,
    installIncoming: @escaping IncomingInstaller
  ) {
    self.outgoingMaterializer = materializeOutgoing
    self.incomingInstaller = installIncoming
  }

  func materializeOutgoing(
    _ reference: CloudDataAssetReference,
    at destinationURL: URL
  ) async throws {
    try await outgoingMaterializer(reference, destinationURL)
  }

  func installIncoming(
    _ reference: CloudDataAssetReference,
    action: CloudDataIncomingAssetAction
  ) async throws {
    try await incomingInstaller(reference, action)
  }
}

/// An opaque package-owned file prepared for an authored replacement intent.
///
/// Prepare this value asynchronously through `CloudDataStore`, then consume it
/// in that store's next authored transaction. It contains no application model
/// or CloudKit SDK value and can cross concurrency boundaries safely.
public struct CloudDataPreparedAssetReplacement: Sendable, Hashable {
  /// The logical slot for which the immutable file was prepared.
  public let reference: CloudDataAssetReference

  let fileID: String
}

/// Asset contract and package staging failures.
public enum CloudDataAssetTransferError: Error, Sendable, Equatable {
  /// The stack was created without consumer filesystem hooks.
  case assetStoreUnavailable

  /// The typed key path was not generated by an `@CloudAsset` property.
  case assetSlotNotRegistered(recordType: String)

  /// A computed slot returned no usable application identifier.
  case emptyLocalIdentifier(recordType: String, fieldKey: String)

  /// A prepared token was consumed by another store, record, or field.
  case preparedAssetMismatch(
    expected: CloudDataAssetReference,
    actual: CloudDataAssetReference
  )

  /// A transfer source was copied or materialized without producing a regular file.
  case stagedFileWasNotMaterialized(URL)

  /// A prepared or durable file identifier was malformed.
  case invalidStagedFileIdentifier(String)

  /// A durable transfer row references a file that no longer exists.
  case stagedFileMissing(fileID: String)
}

/// Package-owned immutable transfer files for one isolated local store.
struct CloudDataAssetFileStore: Sendable {
  let directoryURL: URL

  init(rootDirectoryURL: URL, storeID: CloudDataStoreID) {
    let digest = SHA256.hash(data: Data(storeID.rawValue.utf8))
      .map { String(format: "%02x", $0) }
      .joined()
    self.directoryURL =
      rootDirectoryURL
      .appendingPathComponent("asset-transfers", isDirectory: true)
      .appendingPathComponent(digest, isDirectory: true)
  }

  func materializeOutgoing(
    reference: CloudDataAssetReference,
    using assetStore: CloudDataAssetStore
  ) async throws -> CloudDataPreparedAssetReplacement {
    let fileID = UUID().uuidString
    let destinationURL = try prepareDestination(fileID: fileID)
    do {
      try await assetStore.materializeOutgoing(reference, at: destinationURL)
      guard try isRegularFile(at: destinationURL) else {
        throw CloudDataAssetTransferError.stagedFileWasNotMaterialized(
          destinationURL
        )
      }
      return CloudDataPreparedAssetReplacement(
        reference: reference,
        fileID: fileID
      )
    } catch {
      try? removeFile(fileID: fileID)
      throw error
    }
  }

  /// Copies an already-materialized consumer file into package-owned staging.
  ///
  /// This synchronous path is useful when the domain transaction itself has
  /// just produced the final local file and can name it explicitly. The copied
  /// bytes have the same durable lifetime and revision binding as the async
  /// consumer materializer path.
  func copyOutgoing(
    from sourceURL: URL,
    reference: CloudDataAssetReference
  ) throws -> CloudDataPreparedAssetReplacement {
    let fileID = UUID().uuidString
    let destinationURL = try prepareDestination(fileID: fileID)
    do {
      try FileManager.default.copyItem(at: sourceURL, to: destinationURL)
      guard try isRegularFile(at: destinationURL) else {
        throw CloudDataAssetTransferError.stagedFileWasNotMaterialized(
          destinationURL
        )
      }
      return CloudDataPreparedAssetReplacement(
        reference: reference,
        fileID: fileID
      )
    } catch {
      try? removeFile(fileID: fileID)
      throw error
    }
  }

  func stageIncoming(from sourceURL: URL) throws -> String {
    let fileID = UUID().uuidString
    let destinationURL = try prepareDestination(fileID: fileID)
    do {
      try FileManager.default.copyItem(at: sourceURL, to: destinationURL)
      guard try isRegularFile(at: destinationURL) else {
        throw CloudDataAssetTransferError.stagedFileWasNotMaterialized(
          destinationURL
        )
      }
      return fileID
    } catch {
      try? removeFile(fileID: fileID)
      throw error
    }
  }

  func fileURL(fileID: String) throws -> URL {
    guard UUID(uuidString: fileID) != nil else {
      throw CloudDataAssetTransferError.invalidStagedFileIdentifier(fileID)
    }
    return directoryURL.appendingPathComponent(fileID, isDirectory: false)
  }

  func requireFileURL(fileID: String) throws -> URL {
    let url = try fileURL(fileID: fileID)
    guard try isRegularFile(at: url) else {
      throw CloudDataAssetTransferError.stagedFileMissing(fileID: fileID)
    }
    return url
  }

  func removeFile(fileID: String) throws {
    let url = try fileURL(fileID: fileID)
    guard FileManager.default.fileExists(atPath: url.path) else { return }
    try FileManager.default.removeItem(at: url)
  }

  func removeUntrackedFiles(retaining fileIDs: Set<String>) throws {
    guard FileManager.default.fileExists(atPath: directoryURL.path) else { return }
    for url in try FileManager.default.contentsOfDirectory(
      at: directoryURL,
      includingPropertiesForKeys: [.isRegularFileKey],
      options: [.skipsHiddenFiles]
    ) {
      let fileID = url.lastPathComponent
      guard UUID(uuidString: fileID) != nil else { continue }
      guard fileIDs.contains(fileID) == false else { continue }
      try FileManager.default.removeItem(at: url)
    }
  }

  private func prepareDestination(fileID: String) throws -> URL {
    try FileManager.default.createDirectory(
      at: directoryURL,
      withIntermediateDirectories: true
    )
    let destinationURL = try fileURL(fileID: fileID)
    if FileManager.default.fileExists(atPath: destinationURL.path) {
      try FileManager.default.removeItem(at: destinationURL)
    }
    return destinationURL
  }

  private func isRegularFile(at url: URL) throws -> Bool {
    try url.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile == true
  }
}
