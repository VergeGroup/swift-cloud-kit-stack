import SwiftData

/// A transport-neutral logical handle for one application-owned asset.
///
/// The identifier is interpreted only by the consuming application's asset
/// storage hooks. It is not a file URL, is not persisted by this package, and
/// is never sent to CloudKit.
public struct CloudAssetSlot: Sendable, Hashable {
  /// The stable application identifier used to resolve source and destination
  /// files for this model instance.
  public let localIdentifier: String

  public init(localIdentifier: String) {
    self.localIdentifier = localIdentifier
  }
}

/// An immutable description of one CKAsset-backed record field.
public struct CloudAssetDescriptor: Sendable, Hashable {
  /// The stable field key stored by the remote record.
  public let key: String

  /// The source-written computed property that supplies the logical slot.
  public let propertyName: String

  public init(key: String, propertyName: String) {
    self.key = key
    self.propertyName = propertyName
  }
}

/// A type-erased generated operation for reading one logical asset slot.
///
/// This registration is intentionally non-Sendable because its key path and
/// model instance must remain on the model's owning context or actor.
public struct CloudAssetRegistration {
  /// The concrete application-owned source model type.
  public let sourceModelType: any PersistentModel.Type

  /// The immutable wire and local-slot contract.
  public let descriptor: CloudAssetDescriptor

  private let keyPath: AnyKeyPath
  private let slotImplementation: (any PersistentModel) throws -> CloudAssetSlot

  /// Captures the typed computed slot key path generated by `@CloudAsset`.
  ///
  /// Applications normally receive this operation from `@CloudSynced`
  /// instead of constructing it manually.
  public init<Source: PersistentModel>(
    sourceModelType: Source.Type,
    descriptor: CloudAssetDescriptor,
    slot: KeyPath<Source, CloudAssetSlot>
  ) {
    self.sourceModelType = sourceModelType
    self.descriptor = descriptor
    self.keyPath = slot

    let expectedSourceType = String(reflecting: sourceModelType)
    self.slotImplementation = { source in
      guard let source = source as? Source else {
        throw CloudAssetRegistrationError.sourceModelTypeMismatch(
          expected: expectedSourceType,
          actual: String(reflecting: Swift.type(of: source))
        )
      }
      return source[keyPath: slot]
    }
  }

  /// Returns whether this operation was generated for a typed slot key path.
  public func matches<Source: PersistentModel>(
    _ candidate: KeyPath<Source, CloudAssetSlot>
  ) -> Bool {
    keyPath == candidate
  }

  /// Reads the logical slot from an instance of the registered source type.
  public func slot(
    from source: any PersistentModel
  ) throws -> CloudAssetSlot {
    try slotImplementation(source)
  }
}

/// Misuse errors raised at a generated asset operation boundary.
public enum CloudAssetRegistrationError: Error, Sendable, Equatable {
  /// A slot reader received another source model type.
  case sourceModelTypeMismatch(expected: String, actual: String)
}
